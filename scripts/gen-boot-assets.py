#!/usr/bin/env python3
"""Generate the boot splash theme and bootloader menu art (standard library only).

Usage: scripts/gen-boot-assets.py
Writes two tiny images and the Plymouth scripts of the animated theme and its
reduced-motion variant. Everything is original work, and everything that moves
is computed at boot from scripts/boot_timeline.py, not stored as frames.
tests/test_boot_splash.py checks that the committed files match this generator.
"""

import math
import struct
import sys
import zlib
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import boot_timeline as timeline  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
THEMES = ROOT / "config/includes.chroot/usr/share/plymouth/themes"
BOOTLOADERS = ROOT / "config/bootloaders"
THEMES_IN_IMAGE = "/usr/share/plymouth/themes"
SEED_COLOUR = (225, 235, 255)
SEED_PIXELS = 128
DOT_PIXELS = 16
SEED_STEPS = 12  # pre-scaled seed sizes; the script never scales while animating
FRAME_DIVIDER = 2  # Plymouth refreshes at 50 Hz; the lattice moves at 25
REFRESH_HZ = 50


def seed_alpha(r):
    """A bright core inside a wide, soft halo; r is 0 at the centre, 1 at the edge."""
    if r >= 1.0:
        return 0.0
    return min(1.0, math.exp(-((r / 0.16) ** 2)) + 0.35 * math.exp(-((r / 0.45) ** 2)))


def dot_alpha(r):
    return 0.0 if r >= 1.0 else math.exp(-((r / 0.5) ** 2))


def render_glow(size, alpha, colour=SEED_COLOUR):
    """Return size x size RGBA pixels: one colour, alpha from a radial falloff."""
    half = size / 2
    pixels = bytearray()
    for py in range(size):
        for px in range(size):
            r = math.hypot(px + 0.5 - half, py + 0.5 - half) / half
            pixels.extend(colour)
            pixels.append(int(255 * alpha(r) + 0.5))
    return bytes(pixels)


def png_chunk(kind, body):
    checksum = zlib.crc32(kind + body) & 0xFFFFFFFF
    return struct.pack(">I", len(body)) + kind + body + struct.pack(">I", checksum)


def encode_png_rgba(size, pixels):
    stride = size * 4
    raw = b"".join(b"\x00" + pixels[row * stride : (row + 1) * stride] for row in range(size))
    header = struct.pack(">IIBBBBB", size, size, 8, 6, 0, 0, 0)
    return (
        b"\x89PNG\r\n\x1a\n"
        + png_chunk(b"IHDR", header)
        + png_chunk(b"IDAT", zlib.compress(raw, 9))
        + png_chunk(b"IEND", b"")
    )


def images():
    """The seed, a neutral dot, and one coloured dot per lattice region."""
    files = {
        "seed.png": encode_png_rgba(SEED_PIXELS, render_glow(SEED_PIXELS, seed_alpha)),
        "dot.png": encode_png_rgba(DOT_PIXELS, render_glow(DOT_PIXELS, dot_alpha)),
    }
    for index, colour in enumerate(timeline.REGION_COLOURS):
        pixels = render_glow(DOT_PIXELS, dot_alpha, colour)
        files[f"dot-{index}.png"] = encode_png_rgba(DOT_PIXELS, pixels)
    return files


def number(value):
    return f"{value:.6f}".rstrip("0").rstrip(".")


def theme_definition(name, description):
    return f"""[Plymouth Theme]
Name={name}
Description={description}
ModuleName=script

[script]
ImageDir={THEMES_IN_IMAGE}/spheradian
ScriptFile={THEMES_IN_IMAGE}/{name}/{name}.script
"""


def theme_script(motion):
    """The Plymouth script. It repeats the formulas of boot_timeline.py."""
    t = timeline
    still = t.still_frame()
    breath = " + ".join(
        f"{number(a)} * Math.Sin({number(2 * math.pi * rate)} * t + {number(phase)})"
        for a, rate, phase in t.BREATH
    )
    seed_low = t.SEED_SPECK * (1 - sum(a for a, _, _ in t.BREATH))
    seed_high = t.SEED_FULL * (1 + sum(a for a, _, _ in t.BREATH))
    parallels = "\n".join(f"parallel_lat[{i}] = {lat};" for i, lat in enumerate(t.PARALLELS))
    inner_steps = t.MERIDIAN_STEP // t.DOT_STEP - 1
    regions = "\n".join(
        f'milestone[{i}] = "{name}";  # {meaning}\n'
        f'region_source = Image("dot-{i}.png");\n'
        f"region_image[{i}] = region_source.Scale(dot_width, dot_width);"
        for i, (name, meaning) in enumerate(t.MILESTONES)
    )
    still_place = ", ".join(
        number(still[key]) for key in ("seed_opacity", "seed_size", "reveal_radius", "spin")
    )
    return f"""# SpheradianOS boot splash (docs/BOOT-EXPERIENCE.md, milestones B2 and B3).
# GENERATED by scripts/gen-boot-assets.py from scripts/boot_timeline.py. Do not edit.
#
# A seed of light appears, grows and breathes; its light spreads and reveals a
# lattice of dots on a slowly turning sphere, whose regions wake as the system
# really comes up. Nothing is stored as frames: tiny images placed by arithmetic. \
Esc (boot details) is handled by plymouthd.

motion = {1 if motion else 0};

Window.SetBackgroundTopColor(0, 0, 0);
Window.SetBackgroundBottomColor(0, 0, 0);

side = Window.GetWidth();
if (Window.GetHeight() < side) {{ side = Window.GetHeight(); }}
radius = side * 0.24;
centre_x = Window.GetX() + Window.GetWidth() / 2;
centre_y = Window.GetY() + Window.GetHeight() / 2;
degree = {number(math.pi / 180)};
sin_tilt = {number(math.sin(t.TILT))};
cos_tilt = {number(math.cos(t.TILT))};

# Seed: pre-scaled once, so animating it only swaps images.
seed_source = Image("seed.png");
seed_steps = {SEED_STEPS};
seed_low = {number(seed_low)};
seed_high = {number(seed_high)};
for (i = 0; i < seed_steps; i++) {{
    fraction = seed_low + (seed_high - seed_low) * i / (seed_steps - 1);
    seed_width[i] = Math.Int(radius * 1.2 * fraction) + 2;
    seed_image[i] = seed_source.Scale(seed_width[i], seed_width[i]);
}}
seed = Sprite();
seed.SetOpacity(0);

# Lattice: dots along the meridians, plus the dots between them on the parallels.
dot_width = Math.Int(radius / 14);
if (dot_width < 6) {{ dot_width = 6; }}
dot_source = Image("dot.png");
dot_image = dot_source.Scale(dot_width, dot_width);
dot_count = 0;
for (lon = 0; lon < 360; lon = lon + {t.MERIDIAN_STEP}) {{
    for (lat = {-90 + t.DOT_STEP}; lat < 90; lat = lat + {t.DOT_STEP}) {{
        dot_sin_lat[dot_count] = Math.Sin(lat * degree);
        dot_cos_lat[dot_count] = Math.Cos(lat * degree);
        dot_lon[dot_count] = lon * degree;
        dot_region[dot_count] = Math.Int(lon / {t.REGION_SPAN});
        dot_count++;
    }}
}}
{parallels}
for (p = 0; p < {len(t.PARALLELS)}; p++) {{
    for (lon = 0; lon < 360; lon = lon + {t.MERIDIAN_STEP}) {{
        for (inner = 1; inner <= {inner_steps}; inner++) {{
            dot_sin_lat[dot_count] = Math.Sin(parallel_lat[p] * degree);
            dot_cos_lat[dot_count] = Math.Cos(parallel_lat[p] * degree);
            dot_lon[dot_count] = (lon + inner * {t.DOT_STEP}) * degree;
            dot_region[dot_count] = Math.Int((lon + inner * {t.DOT_STEP}) / {t.REGION_SPAN});
            dot_count++;
        }}
    }}
}}
for (i = 0; i < dot_count; i++) {{
    dot[i] = Sprite(dot_image);
    dot[i].SetOpacity(0);
}}

# Honest progress: systemd reports each service that finishes starting. A region
# of the lattice wakes, taking its colour, when its milestone service is up.
region_count = {len(t.MILESTONES)};
{regions}
for (r = 0; r < region_count; r++) {{
    region_awake[r] = 0;
    region_woke_at[r] = 0;
}}

fun smooth(start, end, t) {{
    u = (t - start) / (end - start);
    if (u < 0) {{ u = 0; }}
    if (u > 1) {{ u = 1; }}
    return u * u * (3 - 2 * u);
}}

fun place(seed_opacity, seed_fraction, reveal, spin, now) {{
    for (r = 0; r < region_count; r++) {{
        level = 0;
        if (region_awake[r]) {{
            level = 1;
            if (motion) {{ level = smooth(region_woke_at[r], \
region_woke_at[r] + {number(t.WAKE_SECONDS)}, now); }}
        }}
        region_glow[r] = {number(t.ASLEEP_GLOW)} + {number(1 - t.ASLEEP_GLOW)} * level;
    }}

    step = Math.Int((seed_fraction - seed_low) / (seed_high - seed_low) * (seed_steps - 1) + 0.5);
    if (step < 0) {{ step = 0; }}
    if (step > seed_steps - 1) {{ step = seed_steps - 1; }}
    seed.SetImage(seed_image[step]);
    seed.SetPosition(centre_x - seed_width[step] / 2, centre_y - seed_width[step] / 2, 0);
    seed.SetOpacity(seed_opacity);

    for (i = 0; i < dot_count; i++) {{
        around = dot_lon[i] + spin;
        x = dot_cos_lat[i] * Math.Sin(around);
        depth = dot_cos_lat[i] * Math.Cos(around);
        y = dot_sin_lat[i] * cos_tilt - depth * sin_tilt;
        z = dot_sin_lat[i] * sin_tilt + depth * cos_tilt;
        lit = 0;
        if (reveal > 0) {{ lit = (reveal * reveal - (x * x + y * y)) / \
({number(2 * t.REVEAL_EDGE)} * reveal); }}
        if (lit < 0) {{ lit = 0; }}
        if (lit > 1) {{ lit = 1; }}
        r = dot_region[i];
        if (region_awake[r]) {{ dot[i].SetImage(region_image[r]); }}
        dot[i].SetOpacity(lit * region_glow[r] * ({number(t.DEPTH_BACK)} + \
{number((t.DEPTH_FRONT - t.DEPTH_BACK) / 2)} * (z + 1)));
        dot[i].SetPosition(centre_x + x * radius - dot_width / 2, \
centre_y - y * radius - dot_width / 2, Math.Int(z * 100));
    }}
}}

tick = 0;
pending = 0;

fun refresh() {{
    global.tick = global.tick + 1;
    global.pending = global.pending + 1;
    if (global.pending >= {FRAME_DIVIDER}) {{
        global.pending = 0;
        t = global.tick / {REFRESH_HZ};
        fraction = ({number(t.SEED_SPECK)} + {number(t.SEED_FULL - t.SEED_SPECK)} * \
smooth(0, {number(t.GATHER_END)}, t)) * (1 + {breath});
        place(smooth(0, {number(t.IGNITE_END)}, t), fraction, \
{number(t.REVEAL_FULL)} * smooth({number(t.REVEAL_START)}, {number(t.GATHER_END)}, t), \
{number(t.SPIN_RATE)} * t, t);
    }}
}}

fun status_update(status) {{
    for (r = 0; r < region_count; r++) {{
        if (status == milestone[r]) {{
            if (region_awake[r] == 0) {{
                global.region_awake[r] = 1;
                global.region_woke_at[r] = global.tick / {REFRESH_HZ};
            }}
        }}
    }}
    # Reduced motion: no animation, but the still frame keeps telling the truth.
    if (motion == 0) {{ place({still_place}, 0); }}
}}

Plymouth.SetUpdateStatusFunction(status_update);

if (motion) {{
    Plymouth.SetRefreshFunction(refresh);
}} else {{
    # Reduced motion: one still frame of the gathered state.
    place({still_place}, 0);
}}
"""


def theme_files():
    """Every generated file, as {path relative to the themes directory: bytes}."""
    files = {f"spheradian/{name}": data for name, data in images().items()}
    files["spheradian/spheradian.plymouth"] = theme_definition(
        "spheradian", "SpheradianOS boot splash: a seed of light reveals the sphere lattice."
    ).encode()
    files["spheradian/spheradian.script"] = theme_script(motion=True).encode()
    files["spheradian-still/spheradian-still.plymouth"] = theme_definition(
        "spheradian-still", "SpheradianOS boot splash, reduced motion: one still frame."
    ).encode()
    files["spheradian-still/spheradian-still.script"] = theme_script(motion=False).encode()
    return files


# --- Bootloader menu art -------------------------------------------------------
#
# ISOLINUX draws its menu background during the hidden half-second timeout on
# every boot, so that background is plain black: the boot stays dark until the
# splash's first speck of light. GRUB draws its theme only when the menu is
# opened, so it can show the sphere: the gathered state, as the splash ends.

ISOLINUX_SIZE = (640, 480)  # vesamenu's graphics mode
GRUB_ART_SIZE = (960, 600)  # 16:10; the theme pads it to any screen, keeping its shape
GRUB_SPHERE_CENTRE = (0.5, 0.31)  # fractions of the width and height
GRUB_SPHERE_RADIUS = 0.2  # fraction of the height
GRUB_ART_GAIN = 0.75  # behind menu text, the art stays below full brightness


def encode_png_rgb(width, height, pixels):
    """8-bit RGB, no interlace, filter 0: a PNG subset both GRUB and vesamenu read."""
    stride = width * 3
    raw = b"".join(b"\x00" + pixels[row * stride : (row + 1) * stride] for row in range(height))
    header = struct.pack(">IIBBBBB", width, height, 8, 2, 0, 0, 0)
    return (
        b"\x89PNG\r\n\x1a\n"
        + png_chunk(b"IHDR", header)
        + png_chunk(b"IDAT", zlib.compress(raw, 9))
        + png_chunk(b"IEND", b"")
    )


def add_glow(canvas, width, height, cx, cy, radius, colour, strength):
    """Additively draw a soft round glow into an RGB float canvas."""
    reach = int(radius * 3) + 1
    for y in range(max(0, int(cy) - reach), min(height, int(cy) + reach + 1)):
        for x in range(max(0, int(cx) - reach), min(width, int(cx) + reach + 1)):
            d2 = ((x + 0.5 - cx) ** 2 + (y + 0.5 - cy) ** 2) / (radius * radius)
            if d2 < 9:
                weight = strength * math.exp(-d2)
                base = (y * width + x) * 3
                for channel in range(3):
                    canvas[base + channel] += colour[channel] * weight


def render_grub_art():
    """The gathered sphere: seed at the centre, every region awake in its colour."""
    width, height = GRUB_ART_SIZE
    canvas = [0.0] * (width * height * 3)
    cx, cy = GRUB_SPHERE_CENTRE[0] * width, GRUB_SPHERE_CENTRE[1] * height
    radius = GRUB_SPHERE_RADIUS * height
    still = timeline.still_frame()
    dots = []
    for lat, lon in timeline.lattice_dots():
        x, y, z = timeline.project(lat, lon, still["spin"])
        region = timeline.region_of(math.degrees(lon))
        dots.append((z, x, y, timeline.REGION_COLOURS[region]))
    for z, x, y, colour in sorted(dots):  # back to front
        strength = 0.9 * timeline.depth_cue(z)
        add_glow(canvas, width, height, cx + x * radius, cy - y * radius, 2.2, colour, strength)
    add_glow(canvas, width, height, cx, cy, radius * 0.09, SEED_COLOUR, 1.0)
    add_glow(canvas, width, height, cx, cy, radius * 0.3, SEED_COLOUR, 0.25)
    return bytes(int(min(255.0, value * GRUB_ART_GAIN) + 0.5) for value in canvas)


def bootloader_files():
    """Generated bootloader files, as {path relative to config/bootloaders: bytes}."""
    black = bytes(ISOLINUX_SIZE[0] * ISOLINUX_SIZE[1] * 3)
    return {
        # Named splash.png so live-build uses it instead of rendering Debian's artwork.
        "isolinux/splash.png": encode_png_rgb(*ISOLINUX_SIZE, black),
        "grub-pc/spheradian/background.png": encode_png_rgb(*GRUB_ART_SIZE, render_grub_art()),
    }


def main():
    for base, files in ((THEMES, theme_files()), (BOOTLOADERS, bootloader_files())):
        for relative, data in files.items():
            path = base / relative
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
            print(f"wrote {path.relative_to(ROOT)} ({len(data)} bytes)")


if __name__ == "__main__":
    main()
